-- Entity:
--   miFPmult4 - floating-point multiplier, radix 16
--
-- Architecture:
--   Combinational multiplier, result = X * Y:
--
--     1. The significands, of R+M bits each (one integer digit), are
--        multiplied as unsigned integers.  The product has two integer
--        digits, and the upper one may be zero.
--     2. Normalization is therefore a shift of zero or one digit, decided
--        by a zero test of the upper digit (tcH): there is no leading-zero
--        counter and no shifter.
--     3. Rounding (Eq. 23 of the paper), removal of the exponent bias and
--        the exponent increment of the normalization are done in a single
--        adder over [exponent | significand].
--     4. The exception field is derived from the operands and from the two
--        bits above the exponent (overflow, underflow).
--
--   The integer product is written with the "*" operator, so that the
--   synthesis tool infers the embedded multipliers (DSP blocks).
--
-- Parameters:
--   Package work.parametros of this folder: R = 4, M = 24, E = 6.
--   The code is generic in R, M and E.
--
-- Ports (X, Y, result):
--   [ exc (2) | sign (1) | exponent (E) | significand (R+M) ]
--     exc         : "00" zero, "01" number, "10" infinity, "11" NaN
--     exponent    : power of 2^R, biased by 2^(E-1)
--     significand : one integer digit D0 (R bits, not zero in a number)
--                   followed by M fractional bits (digits D1 .. Df)
--     value       : (-1)^sign * significand / 2^M * (2^R)^(exponent - 2^(E-1))
--   The sign, exponent and significand fields of a zero, an infinity or a NaN
--   are ignored on input and have no meaning on output.
--
-- Rounding:
--   Eq. (23): the product is truncated to M fractional bits and, when the
--   discarded part is not zero, the least significant bit is added to
--   itself.  The product is exact before rounding, so every result is the
--   correctly rounded one.
--
-- Special cases:
--   NaN if an operand is NaN or for zero * infinity.  Overflow gives
--   infinity and underflow gives zero (there are no subnormal numbers).
--
-- Latency:
--   0 (combinational).
--
-- Reference:
--   J. Villalba and J. Hormigo, "High-Radix Formats for Enhancing Floating-Point
