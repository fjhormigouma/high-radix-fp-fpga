library ieee;
use ieee.std_logic_1164.all;
use ieee.std_logic_arith.all;
use ieee.std_logic_unsigned.all;

library work;
use work.parametros.all;

entity miFPmult4 is
   port ( X      : in  std_logic_vector(2+1+E+M+R-1 downto 0);
          Y      : in  std_logic_vector(2+1+E+M+R-1 downto 0);
          result : out std_logic_vector(2+1+E+M+R-1 downto 0) );
end entity;

architecture arch of miFPmult4 is

   component sOR is
      generic ( N : natural := 24 );
      port ( A : in  std_logic_vector(N-1 downto 0);
             S : out std_logic );
   end component;

   signal sign         : std_logic;
   signal expX, expY   : std_logic_vector(E-1 downto 0);
   signal expSumPreSub : std_logic_vector(E+1 downto 0);            -- sum of the biased exponents
   signal sigX, sigY   : std_logic_vector(M+R-1 downto 0);
   signal sigProd      : std_logic_vector(2*(M+R)-1 downto 0);      -- two integer digits, 2*M fractional bits
   signal excSel       : std_logic_vector(3 downto 0);
   signal exc          : std_logic_vector(1 downto 0);              -- exception from the operands
   signal tcH          : std_logic;                                 -- upper digit of the product is not zero
   signal stk0, stk1   : std_logic;
   signal guard0, guard1 : std_logic;
   signal round        : std_logic;
   signal sigProdNorm  : std_logic_vector(M+R-1 downto 0);          -- normalized, truncated significand
   signal sigProdRd    : std_logic_vector(M+R+E+1 downto 0);        -- [exponent (E+2) | rounded significand]
   signal rndOvf       : std_logic;
   signal sigR         : std_logic_vector(M+R-1 downto 0);
   signal expPrd       : std_logic_vector(E+1 downto 0);
   signal excPostNorm, finalExc : std_logic_vector(1 downto 0);

   -- Added to the upper E+2 bits of the rounding adder, [bias | tcH] is
   -- (-2^(E-1) + tcH) modulo 2^(E+2): it removes one bias from the exponent
   -- sum and adds the normalization increment.
   constant bias : std_logic_vector(E downto 0) := CONV_STD_LOGIC_VECTOR((2**(E+1))-(2**(E-2)),E+1);

begin

   -- Sign, exponents and significands of the operands.
   sign <= X(E+M+R) xor Y(E+M+R);
   expX <= X(E+M+R-1 downto M+R);
   expY <= Y(E+M+R-1 downto M+R);
   sigX <= X(M+R-1 downto 0);
   sigY <= Y(M+R-1 downto 0);

   -- Exponent sum.  It still contains the bias twice; one bias is removed in
   -- the rounding adder below.
   expSumPreSub <= ("00" & expX) + ("00" & expY);

   -----------------------------------------------------------------------------
   -- 1. Significand product: (R+M) x (R+M) -> 2*(R+M) bits.
   --    bits 2(M+R)-1 .. 2M+R : upper integer digit (may be zero)
   --    bits 2M+R-1   .. 2M   : lower integer digit
   --    bits 2M-1     .. 0    : fraction
   -----------------------------------------------------------------------------
   sigProd <= sigX * sigY;

   -- Exception from the classes of the operands (excSel = [excX | excY]).
   excSel <= X(2+1+E+M+R-1 downto 1+E+M+R) & Y(2+1+E+M+R-1 downto 1+E+M+R);
   with excSel select
   exc <= "00" when "0000" | "0001" | "0100",     -- zero * zero, zero * number
          "01" when "0101",                       -- number * number
          "10" when "0110" | "1001" | "1010",     -- infinity * number, infinity * infinity
          "11" when others;                       -- NaN, zero * infinity

   -----------------------------------------------------------------------------
   -- 2. Normalization.  If the upper digit is not zero (tcH = '1') the result
   --    is the upper M+R bits of the product and the exponent is incremented;
   --    otherwise it is taken one digit lower.  For each alternative:
   --      guard = LSB of the bits that are kept
   --      stk   = OR of the bits that are discarded
   -----------------------------------------------------------------------------
   todoceroH : sOR
      generic map ( N => R )
      port map ( A => sigProd(2*(M+R)-1 downto 2*(M+R)-R),
                 S => tcH );

   todoceroL0 : sOR                              -- the M low bits: discarded in both cases
      generic map ( N => M )
      port map ( A => sigProd(M-1 downto 0),
                 S => stk0 );
   guard0 <= sigProd(M);

   todoceroL1 : sOR                              -- one more digit: discarded when tcH = '1'
      generic map ( N => R )
      port map ( A => sigProd(M+R-1 downto M),
                 S => stk1 );
   guard1 <= sigProd(M+R);

   sigProdNorm <= sigProd(2*(M+R)-R-1 downto M) when tcH = '0' else sigProd(2*(M+R)-1 downto M+R);

   -----------------------------------------------------------------------------
   -- 3. Rounding and exponent.  Rounding bit of Eq. (23): (LSB of the kept
   --    part) and (discarded part /= 0).  One adder over [exponent |
   --    significand] adds the rounding bit, removes the bias and adds tcH.
   -----------------------------------------------------------------------------
   round <= (tcH and guard1 and (stk1 or stk0)) or ((not tcH) and guard0 and stk0);

   sigProdRd <= (expSumPreSub & sigProdNorm) + (bias & tcH & CONV_STD_LOGIC_VECTOR(0,M+R-1) & round);
   expPrd    <= sigProdRd(M+R+E+1 downto M+R);

   -- Rounding overflow: the significand was all ones and became all zeros.
   -- The carry has already incremented the exponent, and the significand must
   -- be 1.0, i.e. the LSB of the integer digit is set.  The carry into the
   -- exponent is recovered from the LSB of the exponent sum: the bias has a
   -- zero LSB, so that bit is expSumPreSub(0) xor tcH xor carry.
   rndOvf <= sigProdRd(M+R) xor expSumPreSub(0) xor tcH;
   sigR   <= sigProdRd(M+R-1 downto M+1) & (sigProdRd(M) or rndOvf) & sigProdRd(M-1 downto 0);

   -----------------------------------------------------------------------------
   -- 4. Exceptions.  The two bits above the exponent tell whether it left the
   --    range: "01" overflow (infinity), "1x" negative (underflow, zero).
   --    Zero, infinity and NaN coming from the operands have priority.
   -----------------------------------------------------------------------------
   with expPrd(E+1 downto E) select
   excPostNorm <= "01" when "00",
                  "10" when "01",
                  "00" when others;

   with exc select
   finalExc <= exc         when "11" | "10" | "00",
               excPostNorm when others;

   result <= finalExc & sign & expPrd(E-1 downto 0) & sigR;

end architecture;
