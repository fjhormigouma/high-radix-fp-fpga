-- Entity:
--   miFPAdder6Rnd - floating-point adder/subtractor, radix 64
--
-- Architecture:
--   Combinational adder/subtractor, result = X + Y (invert the sign bit of Y
--   to subtract).  It follows the single-path architecture of Fig. 4 of the
--   paper; because the radix is 2^R, the alignment and normalization shifts
--   move whole digits and are plain multiplexers with very few inputs:
--
--     1. Swap       The operand with the larger exponent becomes X.
--     2. Align      The significand of Y is shifted right d digits (d = exponent
--                   difference).  One guard bit and one sticky bit are kept
--                   below the significand.
--     3. Add        Significand addition or subtraction, depending on the signs.
--                   With equal exponents the difference may be negative.
--     4. Round      A carry out moves the result one digit to the right.  The
--                   rounding of Eq. (23) is applied in a second adder, which
--                   also negates a negative difference.
--     5. Normalize  Leading-zero-digit detection and left shift by digits
--                   (only needed after a subtraction).
--     6. Exponent   +1 after a carry out, -(leading zero digits) otherwise;
--                   overflow gives infinity and underflow gives zero.
--
-- Parameters:
--   Package work.parametros of this folder: R = 6, M = 24, E = 6.
--   The significand has 5 digits (D0.D1 .. D4).  The number of digits is
--   written out in the alignment and normalization multiplexers, so this
--   file is only valid for these values.
--
-- Ports (X, Y, result):
--   [ exc (2) | sign (1) | exponent (E) | significand (R+M) ]
--     exc         : "00" zero, "01" number, "10" infinity, "11" NaN
--     exponent    : power of 2^R, biased by 2^(E-1)
--     significand : one integer digit D0 (R bits, not zero in a number)
--                   followed by M fractional bits (digits D1 .. Df)
--     value       : (-1)^sign * significand / 2^M * (2^R)^(exponent - 2^(E-1))
--   The sign, exponent and significand fields of a zero, an infinity or a NaN
--   are ignored on input and have no meaning on output.
--
-- Rounding:
--   Eq. (23) of the paper: the significand is truncated to M fractional
--   bits and, when the discarded part is not zero, its least significant bit
--   is added to itself.  Rounding is done before normalization.
--
-- Special cases:
--   NaN if an operand is NaN or for infinity - infinity.  There are no
--   subnormal numbers or signed zeros.  Overflow gives infinity and
--   underflow gives zero.
--
-- Limitation:
--   Only two extra bits (guard and sticky) are kept in the alignment, so the
--   adder suffers a high-radix form of catastrophic cancellation: when the
--   exponents differ by one digit and the subtraction cancels the leading
--   digit(s), the result is shifted left by whole digits and up to R-2 bits
--   per digit of the smaller operand, discarded in the alignment, are
--   missing.  The result is normalized but may differ from the exact
--   difference well above the last place, and a tiny non-zero difference
--   may be returned as zero.  See README.md, "Limitations".
--
-- Latency:
--   0 (combinational).
--
-- Reference:
--   J. Villalba and J. Hormigo, "High-Radix Formats for Enhancing Floating-Point
--   FPGA Implementations", Circuits, Systems, and Signal Processing 41,
