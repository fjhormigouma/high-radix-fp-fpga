library ieee;
use ieee.std_logic_1164.all;
use ieee.std_logic_arith.all;
use ieee.std_logic_unsigned.all;

library work;
use work.parametros.all;

entity miFPAdder6Rnd is
   port ( X      : in  std_logic_vector(2+1+E+M+R-1 downto 0);
          Y      : in  std_logic_vector(2+1+E+M+R-1 downto 0);
          result : out std_logic_vector(2+1+E+M+R-1 downto 0) );
end entity;

architecture arch of miFPAdder6Rnd is

   component sOR is
      generic ( N : natural := 24 );
      port ( A : in  std_logic_vector(N-1 downto 0);
             S : out std_logic );
   end component;

   -- Swap and unpacking
   signal excExpX, excExpY : std_logic_vector(2+E-1 downto 0);       -- [exc | exponent] of each input
   signal swap             : std_logic;
   signal newX, newY       : std_logic_vector(2+1+E+M+R-1 downto 0); -- operands after the swap
   signal expX             : std_logic_vector(E-1 downto 0);
   signal excX, excY       : std_logic_vector(1 downto 0);
   signal signX, signY     : std_logic;
   signal EffSub           : std_logic;                              -- effective subtraction
   signal expDiff          : std_logic_vector(E downto 0);           -- exponent of X - exponent of Y (inputs)
   signal fracY            : std_logic_vector(M+R-1 downto 0);       -- significand of the smaller operand
   -- Exceptions and sign
   signal sdsXsYExnXY      : std_logic_vector(5 downto 0);
   signal excRt, excRt2, excR : std_logic_vector(1 downto 0);
   signal exExpExc         : std_logic_vector(3 downto 0);
   signal upExc            : std_logic_vector(1 downto 0);
   signal signR            : std_logic;
   -- Alignment
   signal shiftedFracY     : std_logic_vector(M+R downto 0);         -- aligned significand of Y and guard bit
   signal prestkY          : std_logic_vector(M/R downto 0);         -- prestkY(i) = digit i of Y is not zero
   signal shiftedstkY      : std_logic_vector(M/R downto 0);         -- flags of the digits shifted out
   signal stkY             : std_logic;                              -- sticky bit of the alignment
   -- Addition and rounding
   signal fracAddResult    : std_logic_vector(M+R+2 downto 0);
   signal overF, NstkY, round, NoverF : std_logic;
   signal normfracH        : std_logic_vector(R-1 downto 0);
   signal normfracL        : std_logic_vector(M downto 0);
   signal fracAddResultR   : std_logic_vector(M+R+1 downto 0);
   signal fracAddResultRT  : std_logic_vector(M+R-1 downto 0);
   -- Normalization and exponent
   signal z                : std_logic_vector(M/R downto 0);         -- z(i) = digit i of the result is not zero
   signal allZero          : std_logic;
   signal desp             : std_logic_vector(2 downto 0);           -- number of leading zero digits
   signal fracR0, fracR    : std_logic_vector(M+R-1 downto 0);
   signal extexpR          : std_logic_vector(E+1 downto 0);         -- exponent with two extra bits

begin

   -----------------------------------------------------------------------------
   -- 1. Swap.  X becomes the operand with the larger [exc | exponent] pair, so
   --    that a special value always ends up in X and the alignment shift is
   --    never negative.  The significands are not compared: with equal
   --    exponents the subtraction may give a negative result, which is negated
   --    in the rounding adder (step 4).
   -----------------------------------------------------------------------------
   excExpX <= X(2+1+E+M+R-1 downto 1+E+M+R) & X(E+M+R-1 downto M+R);
   excExpY <= Y(2+1+E+M+R-1 downto 1+E+M+R) & Y(E+M+R-1 downto M+R);
   swap    <= '0' when excExpX >= excExpY else '1';
   newX    <= X when swap = '0' else Y;
   newY    <= Y when swap = '0' else X;

   expX   <= newX(E+M+R-1 downto M+R);
   excX   <= newX(2+1+E+M+R-1 downto 1+E+M+R);
   excY   <= newY(2+1+E+M+R-1 downto 1+E+M+R);
   signX  <= newX(E+M+R);
   signY  <= newY(E+M+R);
   EffSub <= signX xor signY;

   -- Exponent difference of the inputs as they arrive (before the swap): it is
   -- computed in parallel with the swap and only its magnitude is used.
   expDiff <= ("0" & X(E+M+R-1 downto M+R)) - ("0" & Y(E+M+R-1 downto M+R));

   -- A zero takes part in the addition with an all-zero significand.
   fracY <= CONV_STD_LOGIC_VECTOR(0,M+R) when excY = "00" else newY(M+R-1 downto 0);

   -----------------------------------------------------------------------------
   -- Exceptions and sign from the operands alone.
   -- sdsXsYExnXY = [signX | signY | excX | excY].
   -----------------------------------------------------------------------------
   sdsXsYExnXY <= signX & signY & excX & excY;

   with sdsXsYExnXY select
   excRt <= "00" when "000000"|"010000"|"100000"|"110000",                 -- zero + zero
            "01" when "000101"|"010101"|"100101"|"110101"                  -- number + number
                     |"000100"|"010100"|"100100"|"110100"                  -- number + zero
                     |"000001"|"010001"|"100001"|"110001",                 -- zero + number
            "10" when "111010"|"001010"                                    -- infinities of equal sign
                     |"001000"|"011000"|"101000"|"111000"                  -- infinity + zero
                     |"000010"|"010010"|"100010"|"110010"                  -- zero + infinity
                     |"001001"|"011001"|"101001"|"111001"                  -- infinity + number
                     |"000110"|"010110"|"100110"|"110110",                 -- number + infinity
            "11" when others;                                              -- NaN, infinity - infinity

   -- The sign is that of X (the larger operand), inverted when the significand
   -- difference turned out negative (only possible with two numbers of equal
   -- exponent).  Zero + zero of different sign gives +0.
   signR <= '0' when (sdsXsYExnXY = "100000" or sdsXsYExnXY = "010000")
            else (signX xor (fracAddResult(M+R+2) and EffSub and not excX(1)));

   -----------------------------------------------------------------------------
   -- 2. Alignment: Y is shifted right |expDiff| digits.  The multiplexer has
   --    one input per digit position.  The vector keeps one guard bit below
   --    the LSB (bit 0).  When the exponents differ by 5 digits or more,
   --    Y only contributes through the sticky bit (and the guard bit).
   -----------------------------------------------------------------------------
   with CONV_INTEGER(SIGNED(expDiff)) select
      shiftedFracY <= fracY & '0'                                                     when 0,
                      CONV_STD_LOGIC_VECTOR(0,R*1) & fracY(M+R-1 downto R*1-1)    when 1|-1,
                      CONV_STD_LOGIC_VECTOR(0,R*2) & fracY(M+R-1 downto R*2-1)    when 2|-2,
                      CONV_STD_LOGIC_VECTOR(0,R*3) & fracY(M+R-1 downto R*3-1)    when 3|-3,
                      CONV_STD_LOGIC_VECTOR(0,R*4) & fracY(M+R-1 downto R*4-1)    when 4|-4,
                      CONV_STD_LOGIC_VECTOR(0,M+R) & fracY(M+R-1 downto M+R-1) when others;

   -- Sticky bit: OR of the digits of Y that are shifted out.  A "not zero"
   -- flag is computed for every digit and the flags of the lost digits are
   -- selected with the same multiplexer structure.
   calcprestkY : for i in 0 to M/R generate
   begin
      prestkY(i) <= '0' when fracY(R*(i+1)-1 downto R*i) = CONV_STD_LOGIC_VECTOR(0,R) else '1';
   end generate;

   with CONV_INTEGER(SIGNED(expDiff)) select
      shiftedstkY <= CONV_STD_LOGIC_VECTOR(0,5) when 0,
                     prestkY(0 downto 0) & CONV_STD_LOGIC_VECTOR(0,4) when 1|-1,
                     prestkY(1 downto 0) & CONV_STD_LOGIC_VECTOR(0,3) when 2|-2,
                     prestkY(2 downto 0) & CONV_STD_LOGIC_VECTOR(0,2) when 3|-3,
                     prestkY(3 downto 0) & CONV_STD_LOGIC_VECTOR(0,1) when 4|-4,
                     prestkY when others;

   stkY <= '0' when shiftedstkY = CONV_STD_LOGIC_VECTOR(0,5) else '1';

   -----------------------------------------------------------------------------
   -- 3. Significand adder.  Both operands are extended with two bits below the
   --    LSB, [guard | sticky], and one bit above for the carry or the sign:
   --    fracAddResult = [carry/sign | M+R significand bits | guard | sticky].
   -----------------------------------------------------------------------------
   process (newX, shiftedFracY, stkY, EffSub)
   begin
      if EffSub = '0' then
         fracAddResult <= ('0' & newX(M+R-1 downto 0) & "00") + ('0' & shiftedFracY & stkY);
      else
         fracAddResult <= ('0' & newX(M+R-1 downto 0) & "00") - ('0' & shiftedFracY & stkY);
      end if;
   end process;

   -----------------------------------------------------------------------------
   -- 4. Carry out and rounding.
   --    A carry out of an addition (overF) means that the result has one more
   --    integer digit: it is moved one digit to the right, its new leading
   --    digit being 1.  [normfracH | normfracL] is the significand followed by
   --    one extra bit.
   -----------------------------------------------------------------------------
   overF     <= fracAddResult(M+R+2) and not EffSub;
   normfracH <= CONV_STD_LOGIC_VECTOR(1,R) when overF = '1' else fracAddResult(M+R+1 downto M+2);
   normfracL <= fracAddResult(M+R+1 downto R+1) when overF = '1' else fracAddResult(M+1 downto 1);

   -- Sticky bit of the overflow case: OR of the digit shifted out and the two
   -- extra bits.
   NewstkY : sOR
      generic map ( N => R+2 )
      port map ( A => fracAddResult(R+1 downto 0),
                 S => NstkY );

   -- Rounding bit of Eq. (23): (LSB of the kept significand) and (discarded
   -- part /= 0).  Adding it at the LSB position doubles the LSB.
   round <= (not overF and fracAddResult(2) and (fracAddResult(1) or fracAddResult(0)))
            or (overF and fracAddResult(R+2) and NstkY);

   -- Rounding adder.  For a negative difference it computes 0 - result
   -- instead (no rounding is pending in that case: the exponents are equal
   -- and nothing was shifted out).
   -- fracAddResultR = [rounding overflow | M+R significand bits | extra bit].
   process (fracAddResult, EffSub, round, normfracH, normfracL)
   begin
      if (fracAddResult(M+R+2) = '1' and EffSub = '1') then
         fracAddResultR <= (CONV_STD_LOGIC_VECTOR(0,M+R) & round & '0') - ('1' & normfracH & normfracL);
      else
         fracAddResultR <= (CONV_STD_LOGIC_VECTOR(0,M+R) & round & '0') + ('0' & normfracH & normfracL);
      end if;
   end process;
   NoverF          <= fracAddResultR(M+R+1);           -- rounding overflow: the result is 1.0, exponent + 1
   fracAddResultRT <= fracAddResultR(M+R downto 1);    -- rounded significand, not normalized yet

   -----------------------------------------------------------------------------
   -- 5. Normalization.  After a subtraction the leading digits may be zero.
   --    z(i) flags the non-zero digits of the rounded result; a priority
   --    encoder gives the number of leading zero digits (desp) and a
   --    multiplexer shifts the significand left by that number of digits.
   -----------------------------------------------------------------------------
   preLZD : for i in 0 to M/R generate
   begin
      z(i) <= '0' when fracAddResultRT(R*(i+1)-1 downto R*i) = CONV_STD_LOGIC_VECTOR(0,R) else '1';
   end generate;
   allZero <= '1' when z = CONV_STD_LOGIC_VECTOR(0,5) else '0';

   desp <= "000" when z(4) = '1' else
           "001" when z(3) = '1' else
           "010" when z(2) = '1' else
           "011" when z(1) = '1' else
           "100" when z(0) = '1' else
           "000";

   with CONV_INTEGER(desp) select
      fracR0 <= fracAddResultRT                                               when 0,
                fracAddResultRT(M+R-1-R*1 downto 0) & CONV_STD_LOGIC_VECTOR(0,R*1) when 1,
                fracAddResultRT(M+R-1-R*2 downto 0) & CONV_STD_LOGIC_VECTOR(0,R*2) when 2,
                fracAddResultRT(M+R-1-R*3 downto 0) & CONV_STD_LOGIC_VECTOR(0,R*3) when 3,
                fracAddResultRT(M+R-1-R*4 downto 0) & CONV_STD_LOGIC_VECTOR(0,R*4) when others;

   -- After a rounding overflow the significand is exactly 1.0.
   fracR <= fracR0 when NoverF = '0' else CONV_STD_LOGIC_VECTOR(1,R) & CONV_STD_LOGIC_VECTOR(0,M);

   -----------------------------------------------------------------------------
   -- 6. Exponent: +1 after a carry out or a rounding overflow, minus the
   --    number of leading zero digits otherwise.
   -----------------------------------------------------------------------------
   process (overF, NoverF, expX, desp)
   begin
      if (overF = '1' or NoverF = '1') then
         extexpR <= ("00" & expX) + CONV_STD_LOGIC_VECTOR(1,E+2);
      else
         extexpR <= ("00" & expX) - (CONV_STD_LOGIC_VECTOR(0,E+2-3) & desp);
      end if;
   end process;

   -----------------------------------------------------------------------------
   -- Final exception flags.  upExc holds the two bits above the exponent:
   -- "01" overflow (infinity), "1x" negative exponent (underflow, zero).
   -- Infinity and NaN operands are passed on whatever the exponent logic says.
   -----------------------------------------------------------------------------
   upExc    <= extexpR(E+1 downto E);
   exExpExc <= upExc & excRt;
   with exExpExc select
   excRt2 <= "00" when "0000"|"0100"|"1000"|"1100"       -- zero
                      |"1001"|"1101",                    -- number, underflow
             "01" when "0001",                           -- number
             "10" when "0010"|"0110"|"1010"|"1110"       -- infinity
                      |"0101",                           -- number, overflow
             "11" when others;                           -- NaN

   -- A subtraction of two numbers whose significand cancels completely is zero.
   excR <= "00" when (allZero = '1' and EffSub = '1' and excRt = "01") else excRt2;

   result <= excR & signR & extexpR(E-1 downto 0) & fracR;

end architecture;
